// Минимальное R60 изоляции обмоток трансформаторов до 35 кВ в зависимости от температуры (МОм)
const R60_TABLE = [[10, 450], [20, 300], [30, 200], [40, 130], [50, 90], [60, 60], [70, 40]];
function r60Norm(t) {
  if (t === null) return null;
  if (t <= 10) return 450;
  if (t >= 70) return 40;
  for (let i = 0; i < R60_TABLE.length - 1; i++) {
    const [t1, r1] = R60_TABLE[i], [t2, r2] = R60_TABLE[i + 1];
    if (t >= t1 && t <= t2) return Math.round(r1 + (r2 - r1) * (t - t1) / (t2 - t1));
  }
  return null;
}

