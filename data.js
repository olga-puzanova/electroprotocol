function absCheck(r, id, r15, r60, norm) {
  if (!r15 || r60 === null) return;
  const k = r60 / r15;
  if (norm) r[id] = k >= norm ? { value: fmt(k), ok: true, msg: `норма ≥ ${fmt(norm, 1)}` }
    : { value: fmt(k), ...bad(`низкая абсорбция, норма ≥ ${fmt(norm, 1)}`, WET, DRY) };
  else r[id] = k >= 1.3 ? info(fmt(k), 'не нормируется; ≥ 1,3 — изоляция сухая')
    : info(fmt(k), 'низкая абсорбция — возможно увлажнение, рекомендуется сушка');
}

