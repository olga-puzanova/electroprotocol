function num(v) {
  if (v === undefined || v === null || String(v).trim() === '') return null;
  const x = parseFloat(String(v).replace(',', '.'));
  return isNaN(x) ? null : x;
}
const fmt = (x, d = 2) => x.toFixed(d).replace('.', ',');
const OK_OPTIONS = ['Соответствует норме', 'Не соответствует норме', 'Не проводилось'];

// Универсальный пункт испытаний: результат + оценка
function genericItem(i, name) {
  return { title: `${i}. ${name}`, fields: [
    { id: `res_${i}`, label: 'Результат (значения, прибор)', type: 'textarea' },
    { id: `ok_${i}`, label: 'Оценка', type: 'select', required: true, options: OK_OPTIONS }
  ]};
}
// Проверка оценок «соответствует / не соответствует»
function genericChecks(v, r = {}) {
  for (const k of Object.keys(v)) {
    if (!/^ok_\d+$/.test(k)) continue;
    if (v[k] === 'Соответствует норме') r[k] = { ok: true, msg: 'в норме' };
    if (v[k] === 'Не соответствует норме') r[k] = { ok: false, msg: 'не соответствует норме' };
  }
  return r;
}
const hasHV = items => items.some(s => /повышенн/i.test(s));

// Минимальное R60 изоляции обмоток трансформаторов до 35 кВ в зависимости от температуры (МОм)
const R60_TABLE = [[10, 450], [20, 300], [30, 200], [40, 130], [50, 90], [60, 60], [70, 40]];
function r60Norm(t) {
  if (t === null) return null;
  if (t <= 10) return 450;
  if (t >= 70) return 40;
  for (let i = 0; i < R60_TABLE.length - 1; i++) {
    const [t1, r1] = R60_TABLE[i], [t2, r2] = R60_TABLE[i + 1];
    if (t >= t1 && t <= t2) return Math.round(r1 + (r2 - r1) * (t - t1) / (t2 - t1));
  }
  return null;
}

